"""Phase 2 — One-time LLM semantic annotation of profiled columns.

Takes the raw statistical profiles produced by :mod:`data_profiler` and
enriches them with human-readable descriptions, value meanings, and
natural-language aliases — all generated by a single batched LLM call
**per table** (not per column).

The output is a ``dict`` keyed by column name, each containing:

  - ``description``:         Plain-English column purpose.
  - ``value_descriptions``:  ``{raw_value: meaning}`` for coded/abbreviated values.
  - ``natural_language_aliases``:  ``{alias: raw_value}`` a user might say.
  - ``query_hints``:         Advice for the SQL generator (exact match, LIKE, etc.)

Usage::

    from app.semantic_catalog.semantic_annotator import SemanticAnnotator

    annotator = SemanticAnnotator()
    enriched = annotator.annotate_table(
        table_name="sales.sample",
        columns_schema={...},       # from schema config
        columns_profile={...},      # from DataProfiler
    )
"""

from __future__ import annotations

import json
import logging
import os
from typing import Any

from langchain_core.prompts import ChatPromptTemplate
from langchain_openai import ChatOpenAI
from pydantic import SecretStr

from app.envsetup.env_loader import get_openai_api_key

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Prompt template
# ---------------------------------------------------------------------------

_ANNOTATION_SYSTEM_PROMPT = """\
You are a data catalog expert.  You will be given a database table name,
its column schemas, and statistical profiles of each column's actual data.

Your job is to generate a **semantic annotation** for each column so that
a downstream NL-to-SQL system can map human language to exact database values.

For each column, return a JSON object with these keys:

  "description"              — One-sentence plain-English purpose of this column.
  "value_descriptions"       — (TEXT columns only, when values are coded/abbreviated)
                                A mapping of raw DB value → human-readable meaning.
                                Only include entries where the raw value is NOT already
                                self-explanatory.  Return {{}} if values are clear.
  "natural_language_aliases" — A mapping of natural language phrase (lowercase) →
                                raw DB value.  These are words a user might type
                                that should resolve to a specific DB value.
                                Return {{}} if not applicable.
  "query_hints"              — A short instruction for the SQL generator about how
                                to filter on this column.  Examples:
                                "Use exact match with coded value."
                                "Case-insensitive ILIKE recommended."
                                "Use DATE_TRUNC for period queries."
                                "High cardinality — consider ILIKE or fuzzy match."

Return ONLY a JSON object keyed by column name.  No markdown.  No explanation.
"""

_ANNOTATION_USER_TEMPLATE = """\
Table: {table_name}

Column Schemas:
{columns_schema_text}

Column Profiles:
{columns_profile_text}

Generate the semantic annotation JSON for every column listed above.
"""


class SemanticAnnotator:
    """Generates semantic annotations for profiled columns using an LLM.

    Parameters
    ----------
    model : str | None
        OpenAI model name.  Falls back to the project-wide configured model.
    temperature : float
        LLM sampling temperature — keep low for deterministic output.
    """

    def __init__(
        self,
        model: str | None = None,
        temperature: float = 0.0,
    ) -> None:
        self._llm = ChatOpenAI(
            model=model or os.getenv("OPENAI_MODEL", "gpt-4o").strip().strip("'\""),
            temperature=temperature,
            api_key=SecretStr(get_openai_api_key()),
        )
        self._prompt = ChatPromptTemplate.from_messages([
            ("system", _ANNOTATION_SYSTEM_PROMPT),
            ("user", _ANNOTATION_USER_TEMPLATE),
        ])

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def annotate_table(
        self,
        table_name: str,
        columns_schema: dict[str, dict[str, Any]],
        columns_profile: dict[str, dict[str, Any]],
    ) -> dict[str, dict[str, Any]]:
        """Annotate all columns of a single table.

        Parameters
        ----------
        table_name:
            Qualified table name (e.g. ``"public.sales_sample"``).
        columns_schema:
            Column metadata from the schema config
            (``{col_name: {"type": ..., "notnull": ..., ...}}``).
        columns_profile:
            Output of ``DataProfiler.profile_table()``
            (``{col_name: {"cardinality": ..., "distinct_values": [...], ...}}``).

        Returns
        -------
        dict
            ``{col_name: {"description": ..., "value_descriptions": ..., ...}}``
        """
        # Build compact text representations for the prompt
        schema_text = _format_columns_schema(columns_schema)
        profile_text = _format_columns_profile(columns_profile)

        messages = self._prompt.format_messages(
            table_name=table_name,
            columns_schema_text=schema_text,
            columns_profile_text=profile_text,
        )

        logger.info("Requesting semantic annotation for table %s …", table_name)
        response = self._llm.invoke(messages)
        raw_content = (
            response.content
            if isinstance(response.content, str)
            else str(response.content)
        )

        return _parse_annotation_response(raw_content, list(columns_schema.keys()))

    def annotate_tables(
        self,
        tables_schema: dict[str, dict[str, Any]],
        tables_profile: dict[str, dict[str, dict[str, Any]]],
    ) -> dict[str, dict[str, dict[str, Any]]]:
        """Annotate multiple tables.  One LLM call per table.

        Parameters
        ----------
        tables_schema:
            ``{qualified_table_name: {"columns": {...}, ...}}``
        tables_profile:
            Output of ``DataProfiler.profile_tables()``.

        Returns
        -------
        dict
            ``{qualified_table_name: {col_name: annotation, ...}, ...}``
        """
        result: dict[str, dict[str, dict[str, Any]]] = {}

        for table_name, table_info in tables_schema.items():
            columns_schema = table_info.get("columns", {})
            columns_profile = tables_profile.get(table_name, {})

            if not columns_schema:
                logger.warning("No columns for %s, skipping annotation.", table_name)
                continue

            try:
                result[table_name] = self.annotate_table(
                    table_name, columns_schema, columns_profile,
                )
            except Exception:
                logger.exception("Annotation failed for table %s", table_name)
                result[table_name] = {}

        return result


# ---------------------------------------------------------------------------
# Formatting helpers — keep prompt tokens small
# ---------------------------------------------------------------------------

def _format_columns_schema(columns: dict[str, dict[str, Any]]) -> str:
    """Render column schemas as a compact multi-line string."""
    lines: list[str] = []
    for name, meta in columns.items():
        dtype = meta.get("type", "UNKNOWN")
        nullable = "NULL" if not meta.get("notnull") else "NOT NULL"
        pk = " PK" if meta.get("is_pk") else ""
        lines.append(f"  {name}: {dtype} {nullable}{pk}")
    return "\n".join(lines)


def _format_columns_profile(profiles: dict[str, dict[str, Any]]) -> str:
    """Render column profiles as a compact multi-line string.

    Truncates large value lists to keep the prompt within token limits.
    """
    lines: list[str] = []

    for name, profile in profiles.items():
        ptype = profile.get("profile_type", "unknown")

        if ptype == "text":
            card = profile.get("cardinality", "?")
            null_pct = profile.get("null_ratio", 0)
            vals = profile.get("distinct_values") or [
                v["value"] for v in profile.get("top_values", [])[:30]
            ]
            # Truncate if too many
            shown = vals[:50]
            suffix = f" … (+{len(vals) - 50} more)" if len(vals) > 50 else ""
            lines.append(
                f"  {name}: TEXT | cardinality={card} | nulls={null_pct:.1%}"
                f" | values={shown}{suffix}"
            )

        elif ptype == "numeric":
            lines.append(
                f"  {name}: NUMERIC | "
                f"min={profile.get('min_value')} max={profile.get('max_value')} "
                f"mean={profile.get('mean_value')} median={profile.get('median_value')} "
                f"nulls={profile.get('null_ratio', 0):.1%}"
            )

        elif ptype == "temporal":
            lines.append(
                f"  {name}: TEMPORAL | "
                f"range={profile.get('min_date')} → {profile.get('max_date')} | "
                f"granularity={profile.get('granularity')} | "
                f"nulls={profile.get('null_ratio', 0):.1%}"
            )

        else:
            lines.append(f"  {name}: ({ptype})")

    return "\n".join(lines)


def _parse_annotation_response(
    raw: str,
    expected_columns: list[str],
) -> dict[str, dict[str, Any]]:
    """Parse the LLM JSON response, tolerating markdown fences."""
    cleaned = raw.strip()
    # Strip markdown code fences if present
    if cleaned.startswith("```"):
        first_newline = cleaned.index("\n")
        cleaned = cleaned[first_newline + 1:]
    if cleaned.endswith("```"):
        cleaned = cleaned[: cleaned.rfind("```")]
    cleaned = cleaned.strip()

    try:
        parsed = json.loads(cleaned)
    except json.JSONDecodeError:
        logger.error("Failed to parse annotation JSON:\n%s", cleaned[:500])
        return {col: {} for col in expected_columns}

    if not isinstance(parsed, dict):
        logger.error("Annotation response is not a dict: %s", type(parsed))
        return {col: {} for col in expected_columns}

    # Ensure every expected column has an entry
    for col in expected_columns:
        if col not in parsed:
            parsed[col] = {}

    return parsed
